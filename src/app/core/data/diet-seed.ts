  function buildMeal(
    name: string,
    time: string,
    targetKcal: number,
    items: ReturnType<typeof foodRef>[],
    note?: string,
  ): Meal {
    const sumKcal = Math.round(items.reduce((s, i) => s + i.kcal, 0));
    const proteinG = Math.round(items.reduce((s, i) => s + i.proteinG, 0) * 10) / 10;
    const carbG = Math.round(items.reduce((s, i) => s + i.carbG, 0) * 10) / 10;
    const fatG = Math.round(items.reduce((s, i) => s + i.fatG, 0) * 10) / 10;
    const fiberG = Math.round(items.reduce((s, i) => s + i.fiberG, 0) * 10) / 10;
    return {
      name,
      time,
      kcal: items.length > 0 ? sumKcal : targetKcal,
      proteinG,
      carbG,
      fatG,
      fiberG,
      items,
      note,
    };
  }

